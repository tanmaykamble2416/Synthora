"""Migration round trip and model/migration drift, on the test DB only."""

import asyncio

from alembic.config import Config
from sqlalchemy import text
from sqlalchemy.engine import URL
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.pool import NullPool

from alembic import command

APP_TABLES = {"users", "workspaces", "papers", "paper_sections", "paper_chunks"}


def _query(url: URL, sql: str) -> list[tuple]:
    async def run() -> list[tuple]:
        engine = create_async_engine(url, poolclass=NullPool)
        try:
            async with engine.connect() as conn:
                return [tuple(r) for r in (await conn.execute(text(sql))).all()]
        finally:
            await engine.dispose()

    return asyncio.run(run())


def _tables(url: URL) -> set[str]:
    return {r[0] for r in _query(url, "SELECT tablename FROM pg_tables WHERE schemaname = 'public'")}


def test_upgrade_downgrade_upgrade_round_trip(alembic_config: Config, test_db_url: URL) -> None:
    assert APP_TABLES <= _tables(test_db_url)

    command.downgrade(alembic_config, "base")
    assert not (APP_TABLES & _tables(test_db_url))
    # Downgrade must not remove the pgvector extension.
    assert _query(test_db_url, "SELECT extname FROM pg_extension WHERE extname = 'vector'") == [("vector",)]

    command.upgrade(alembic_config, "head")
    assert APP_TABLES <= _tables(test_db_url)
    assert _query(test_db_url, "SELECT version_num FROM alembic_version") == [("0001",)]


def test_models_match_migrations(alembic_config: Config) -> None:
    # Raises AutogenerateDiffsDetected if models and migrations have drifted apart.
    command.check(alembic_config)


def test_composite_foreign_keys_exist_as_designed(test_db_url: URL) -> None:
    rows = _query(
        test_db_url,
        "SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint "
        "WHERE conrelid = 'paper_chunks'::regclass AND contype = 'f' ORDER BY conname",
    )
    assert rows == [
        (
            "fk_paper_chunks_paper_id_workspace_id_papers",
            "FOREIGN KEY (paper_id, workspace_id) REFERENCES papers(id, workspace_id) ON DELETE CASCADE",
        ),
        (
            "fk_paper_chunks_section_id_paper_id_paper_sections",
            "FOREIGN KEY (section_id, paper_id) REFERENCES paper_sections(id, paper_id) "
            "ON DELETE SET NULL (section_id)",
        ),
    ]


def test_no_vector_columns_yet(test_db_url: URL) -> None:
    rows = _query(
        test_db_url,
        "SELECT table_name, column_name FROM information_schema.columns "
        "WHERE table_schema = 'public' AND udt_name = 'vector'",
    )
    assert rows == []
